export function createGuide() {
 const expandFields = (text)=>Object.entries(fieldLayouts).reduce((result, [key, gen])=>{
  const source = gen().trim();
  const demo = source.replace('chapterOpener,wide', 'chapterOpener,compact').replace('briefingSheet,wide', 'briefingSheet').replace('mapSheet,wide', 'mapSheet');
  return result.replaceAll('__FIELD_' + key.toUpperCase() + '__', source).replaceAll('__DEMO_' + key.toUpperCase() + '__', demo);
 }, text);
 return { ...emptyDocument(pages.map((lines)=>expandFields(lines.join('\n').replaceAll('__GUIDE_CHAPTER__', fieldLayouts.chapter().trim().replace('### Chapter title', '### Chapter Opener').replace('A short subtitle or briefing classification.', 'A full-page divider for the next stage of your operation.')).replaceAll('__PHOTO_ASSET__', asset('dg-photo-placeholder.svg')).replaceAll('__TIMELINE__', timeline().trim()).replaceAll('__TOME__', tome().trim()).replaceAll('__PINK__', pink().trim()).replaceAll('__PINK_COLUMN__', pink().trim().replace('pinkBackground,wide', 'pinkBackground')))).join('\n\n\\page\n\n')), title: 'Delta Greenery Guide', style: '.page .guideEvidence { border-left: 3px solid #742f25; padding: 10px; background: #ffffff50; }\n\n/* Optional: hide the section name in the running header. Remove the comment markers to enable.\n.page .runningHeader .sectionTitle { display: none; }\n*/\n\n/* Optional: a different printed title.\n.page { --HB_DocTitle: "BLACK LANTERN"; }\n*/', snippets: '\\snippet Evidence note\n{{note\n##### Evidence\nDescribe the discovery here.\n}}' };
}
